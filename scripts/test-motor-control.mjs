import { motorPracticalAdditions, solarAdditions } from './assert-c2-reorganization.mjs';
const motorPracticalIds = new Set([...motorPracticalAdditions, ...solarAdditions].map(v => v.id));
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { build } from 'esbuild';

const read = path => JSON.parse(fs.readFileSync(path, 'utf8'));
await build({ entryPoints: ['app/personal-course-model.ts', 'app/course-progress-model.ts', 'app/course-curriculum.ts'], outdir: 'work/motor-control-tests', bundle: true, platform: 'node', format: 'esm' });
const { publishedPersonalCourse: base, parsePersonalCourse: parse, personalCourseSnapshot: snapshot, applyCourseEdit: apply, migratePersonalCourse } = await import('../work/motor-control-tests/personal-course-model.js');
const { progressForVideos } = await import('../work/motor-control-tests/course-progress-model.js');
const prior = read('scripts/fixtures/motor-control-previous.json'), original = structuredClone(prior);
const update = read('app/motor-control-update.json'), catalog = read('app/video-catalog.json'), sections = read('app/learning-sections.json');
const evidence = read('docs/motor-control-video-review.json');
const added = new Set(update.addedLessonIds), upgraded = parse(prior), view = snapshot(upgraded);
const section = sections.find(section => section.id === update.sectionIds[0]);
const core = new Map(catalog.modules.flatMap(module => module.lessons).map(lesson => [lesson.id, lesson]));
const motorModule = catalog.modules.find(module => module.id === section.moduleId);
assert.equal(prior.curriculumRevision, 13);
assert.equal(upgraded.curriculumRevision, 14);
assert.deepEqual(prior, original);
assert.deepEqual(upgraded.groups, base.groups);
assert.deepEqual(parse(upgraded), upgraded);
assert.equal(section.title, 'Motor control');
assert.equal(section.number, 1);
assert.equal(motorModule.id, 'module-07');
assert.equal(motorModule.title, 'Motor Starting, Protection and Speed Control');
assert.equal(motorModule.stageNumber, 13, 'Use the current motor-control module number');
assert.equal(sections.find(section => section.moduleId === motorModule.id).id, section.id);
assert.deepEqual(section.lessonIds, update.addedLessonIds);
assert.equal(added.size, 24);
assert.equal(section.description, undefined, 'No new learner-facing notes or introduction');
for (const id of added) assert.equal(core.get(id).studyNote, undefined, 'Videos and ordering only, as requested');
assert.deepEqual(update.blocks.flatMap(block => block.lessonIds), section.lessonIds);
const videoIds = ids => ids.map(id => core.get(id).videoId);
assert.deepEqual(videoIds(update.blocks[0].lessonIds), ['HFkTPmY7N7w', 'cPQ9X0clG6w', '_uz2bxi-vdY', 'J0rs0vSLpRk', 'xIz-YhrLAFU']);
assert.deepEqual(videoIds(update.blocks[1].lessonIds), ['bkboBItqFXE', 'Ed3_zbZ0xaA']);
assert.deepEqual(videoIds(update.blocks[2].lessonIds), ['7U-DqKQkSPU', 'PIaqmCxN9KU', '5wNm48d2jLU', 'Shs9lTnZVCU', 'mcXxhUaUb94', 'qlqPdLGwJxk', 'CuOjpBwJ8n0', 'Y20len0l-G8', '0u2gW4lIbes', 'HwGLVNWetyw', 'TNQBFWo45tg', 'd5uFPkCc-FA', 'U46n_BnaqoI', 'BKscdOuu4tk', 'koUtbPZWVaM', 'NRqI-lDUfL0', 'QWsxYqwtYCc']);
for (const block of update.blocks) assert.ok(block.lessonIds.every(id => core.get(id).instructor === block.instructor));
for (const [id, ids] of Object.entries(prior.groups)) assert.deepEqual(upgraded.groups[id], ids, 'Existing focused sections and mixed saved order stay unchanged: ' + id);
assert.deepEqual(Object.values(upgraded.groups).flat().filter(id => !added.has(id) && !motorPracticalIds.has(id)).sort(), Object.values(prior.groups).flat().sort());
assert.equal(view.allRows.length, 572);
assert.equal(catalog.lessonCount, 540);
assert.equal(sections.length, 227);
assert.equal(view.allRows.filter(row => view.course.modules.find(module => module.id === row.moduleId).path === 'C1').length, 212);
const rows = view.allRows.filter(row => row.moduleId === motorModule.id);
assert.deepEqual(rows.slice(0, 24).map(row => row.id), section.lessonIds);
assert.equal(rows[24].id, 'p04-l21', 'Focused topics follow the complete creator sequences');
assert.deepEqual(rows.map(row => row.displayNumber), rows.map((_, index) => index + 1));
assert.equal(progressForVideos(section.lessonIds, new Set(['p04-l21', 'p04-l19', 'course-HFkTPmY7N7w'])).watched, 0, 'Repeated videos have independent watched occurrences');
assert.deepEqual(evidence.videos.map(video => video.lessonId), section.lessonIds);
for (const video of evidence.videos) {
  assert.equal(video.videoId, core.get(video.lessonId).videoId);
  assert.match(video.transcript.sha256, /^[a-f0-9]{64}$/);
  assert.ok(video.transcript.reviewedRanges.every(range => range.endSeconds > range.startSeconds && range.endSeconds <= video.transcript.captionEndSeconds));
  if (video.transcript.language.includes('ar')) assert.match(video.transcript.reviewQualification, /translated Arabic/);
}

const custom = structuredClone(prior);
custom.revision = 71;
custom.groups['c1-controls-three-phase-dol'].reverse();
custom.groups['module-07-section-1'] = custom.groups['module-07-section-1'].filter(id => id !== 'course-HFkTPmY7N7w');
custom.groups['module-01-section-1'].push('course-HFkTPmY7N7w');
custom.itemRevisions['course-HFkTPmY7N7w'] = 71;
const copy = { id: 'private-motor-control', videoId: 'bkboBItqFXE', title: 'My own contactor lesson', instructor: 'My saved teacher', moduleId: 'module-01', anchorId: 'module-01-section-1', position: 'after', archived: true, placementRevision: 13, updatedAt: '2026-10-25T10:00:00Z' };
custom.videos.push(copy); custom.groups['module-01-section-1'].push(copy.id);
custom.archivedLessonIds = ['p04-l19']; custom.deletedIds = ['p15-v2-l01'];
custom.receipts = [{ id: 'before-motor-section', revision: 71, affected: ['course-HFkTPmY7N7w'], inverse: { positions: [{ id: 'course-HFkTPmY7N7w', sectionId: 'module-07-section-1', beforeId: null, afterId: 'p04-l21' }], videos: [], archiveIds: [] } }];
const kept = parse(custom);
for (const [id, ids] of Object.entries(custom.groups)) assert.deepEqual(kept.groups[id], ids.filter(id => !custom.deletedIds.includes(id)));
assert.deepEqual(kept.videos.find(video => video.id === copy.id), copy);
for (const key of ['revision', 'itemRevisions', 'receipts', 'archivedLessonIds', 'deletedIds']) assert.deepEqual(kept[key], custom[key]);
assert.deepEqual(parse(kept), kept);
const change = (state, edit) => apply(state, { operationId: crypto.randomUUID(), revision: state.revision, edit });
const undone = change(kept, { type: 'undo', targetOperationId: 'before-motor-section' });
assert.equal(snapshot(undone).byId.get('course-HFkTPmY7N7w').sectionId, 'module-07-section-1');
const moved = change(upgraded, { type: 'move', id: section.lessonIds[0], sectionId: 'module-01-section-1', beforeId: null });
assert.equal(snapshot(parse(moved)).byId.get(section.lessonIds[0]).sectionId, 'module-01-section-1', 'A later personal move is not replayed');
const removed = change(moved, { type: 'delete', id: section.lessonIds[1] });
assert.ok(!snapshot(parse(removed)).byId.has(section.lessonIds[1]));
const archived = change(removed, { type: 'archive', id: section.lessonIds[2] });
assert.ok(!snapshot(parse(archived)).byId.has(section.lessonIds[2]));
const legacy = { version: 1, revision: 8, curriculumRevision: 13, groups: Object.fromEntries(Object.entries(prior.groups).map(([id, ids]) => [id, ids.filter(id => core.has(id))])) };
assert.deepEqual(migratePersonalCourse(legacy, { version: 1, revision: 8, videos: prior.videos }).groups, base.groups);
