  await page.keyboard.press('ArrowLeft');
  await page.getByRole('heading', { name: 'Question 1 — Electrical Current' }).waitFor();
  await button('Flag for later').click();
  await page.getByRole('checkbox', { name: 'Flagged / needs revision' }).check();
  assert.equal(await page.getByRole('navigation', { name: 'Questions', exact: true }).getByRole('button').count(), 1);
  await page.getByRole('checkbox', { name: 'Flagged / needs revision' }).uncheck();
  await page.getByRole('textbox', { name: 'Find a question' }).fill('voltage');
  const first = await page.locator('.epra-question-card > h2').textContent();
  await button('Next question').click();
  assert.notEqual(await page.locator('.epra-question-card > h2').textContent(), first);
  await page.getByRole('textbox', { name: 'Find a question' }).fill('');
  await page.getByRole('button', { name: /Quiz me/ }).click();
  assert.equal(await page.getByRole('navigation', { name: 'Questions', exact: true }).getByRole('button').count(), 10);
  assert.equal(await page.getByRole('button', { name: /^Reveal Answer/ }).count(), 0, 'Quiz solutions locked');
  await page.locator('#epra-working').fill('My independent attempt.');
  await button('Finish quiz & review').click();
  await button('Finish & review answers').click();
  assert.equal(await page.locator('#epra-working').getAttribute('readonly'), '');
  if (await page.getByRole('button', { name: /^Reveal Answer/ }).count()) await page.getByRole('button', { name: /^Reveal Answer/ }).click();
