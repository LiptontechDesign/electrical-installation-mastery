import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { progressFixture } from './course-progress-fixture.mjs';

await build({ entryPoints: ['app/course-progress-model.ts', 'app/personal-course-model.ts', 'app/learner-state.ts', 'app/flexible-progress.ts'], outdir: 'work/progress-tests', bundle: true, platform: 'node', format: 'esm' });
const { progressForVideos } = await import('../work/progress-tests/course-progress-model.js');
const model = await import('../work/progress-tests/personal-course-model.js');
const publishedBefore = JSON.stringify(model.publishedPersonalCourse);
const { initialLearnerState } = await import('../work/progress-tests/learner-state.js');
const { recordVideoCompletion } = await import('../work/progress-tests/flexible-progress.js');
const seed = progressFixture(model);
let state = seed.state;
let learner = { ...initialLearnerState, completedLessonIds: [seed.coreIds[0], 'p01-l01', 'old-deleted-lesson'] };
let supplementaryWatched = [];
const snapshot = () => model.personalCourseSnapshot(state);
const watched = () => new Set([...learner.completedLessonIds, ...snapshot().videos.filter(video => supplementaryWatched.includes(video.videoId)).map(video => video.id)]);
const progress = (rows = snapshot().allRows) => progressForVideos(rows.map(row => row.id), watched());
const check = (expected, message) => assert.deepEqual(progress(), expected, message);
const edit = operation => { state = model.applyCourseEdit(state, { operationId: crypto.randomUUID(), revision: state.revision, edit: operation }); };
const restore = id => edit({ type: 'restore', id, sectionId: seed.sectionId, beforeId: null });

check({ total: 5, watched: 1, percent: 20 }, 'Archived historical marks do not count; all active video types do');
learner = recordVideoCompletion(learner, seed.coreIds[2]);
check({ total: 5, watched: 2, percent: 40 }, 'Optional catalogue completion contributes');
learner = recordVideoCompletion(learner, seed.coreIds[2]);
check({ total: 5, watched: 2, percent: 40 }, 'Replay events never inflate unique progress');
assert.equal(learner.videoCompletionCounts[seed.coreIds[2]], 2);
supplementaryWatched = [seed.added[0].videoId];
check({ total: 5, watched: 3, percent: 60 }, 'Personal supplementary marks contribute');
supplementaryWatched = [];
check({ total: 5, watched: 2, percent: 40 }, 'Undoing a supplementary mark updates progress');
supplementaryWatched = [seed.added[0].videoId];
edit({ type: 'archive', id: seed.coreIds[0] });
check({ total: 4, watched: 2, percent: 50 }, 'Archiving a watched video removes both numerator and denominator');
restore(seed.coreIds[0]);
check({ total: 5, watched: 3, percent: 60 }, 'Restore recovers the saved watched mark');
edit({ type: 'archive', id: seed.coreIds[1] });
check({ total: 4, watched: 3, percent: 75 }, 'Archiving an unwatched video changes only the denominator');
restore(seed.coreIds[1]);

edit({ type: 'move', id: seed.added[0].id, sectionId: seed.destination, beforeId: null });
check({ total: 5, watched: 3, percent: 60 }, 'Moving between pathways preserves overall progress');
assert.deepEqual(progress(snapshot().rows[seed.sectionId]), { total: 4, watched: 2, percent: 50 });
assert.deepEqual(progress(snapshot().rows[seed.destination]), { total: 1, watched: 1, percent: 100 });
state = model.parsePersonalCourse(JSON.parse(JSON.stringify(state)));
check({ total: 5, watched: 3, percent: 60 }, 'Reload preserves moved and archived counts');
edit({ type: 'delete', id: seed.coreIds[0] });
check({ total: 4, watched: 2, percent: 50 }, 'Deleting a watched video removes both counts');
assert.ok(learner.completedLessonIds.includes(seed.coreIds[0]), 'Private history is preserved');
edit({ type: 'delete', id: seed.coreIds[1] });
check({ total: 3, watched: 2, percent: 67 }, 'Deleting an unwatched video changes the denominator');
edit({ type: 'delete', id: seed.added[0].id });
check({ total: 2, watched: 1, percent: 50 }, 'Deleted supplementary IDs cannot count retained marks');
edit({ type: 'add', url: 'https://youtu.be/' + seed.added[0].videoId, title: 'Re-added electrode video', instructor: '', sectionId: seed.sectionId, beforeId: null });
check({ total: 3, watched: 2, percent: 67 }, 'Re-adding a YouTube video restores its stable watched record');
for (const row of snapshot().allRows) edit({ type: 'archive', id: row.id });
check({ total: 0, watched: 0, percent: 0 }, 'An empty course has finite zero progress');
restore(seed.added[1].id);
check({ total: 1, watched: 0, percent: 0 }, 'A supplementary-only course has an accurate total');
assert.deepEqual(progressForVideos(['a', 'a', 'b'], new Set(['a', 'removed'])), { total: 2, watched: 1, percent: 50 });
assert.equal(JSON.stringify(model.publishedPersonalCourse), publishedBefore, 'Personal edits do not change the published course');
console.log('PASS: mixed-video progress, replay/undo, watched/unwatched archive and deletion, restore, movement, reload, retained identity, empty and supplementary-only courses.');
