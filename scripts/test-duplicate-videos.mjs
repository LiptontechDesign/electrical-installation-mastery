import assert from 'node:assert/strict';
import { build } from 'esbuild';
await build({entryPoints:['app/personal-course-model.ts'],outfile:'work/duplicate-tests/model.mjs',bundle:true,platform:'node',format:'esm'});
const {publishedPersonalCourse,parsePersonalCourse,personalCourseSnapshot,applyCourseEdit}=await import('../work/duplicate-tests/model.mjs');
const change=(state,edit)=>applyCourseEdit(state,{revision:state.revision,operationId:crypto.randomUUID(),edit});
const section='module-01-section-1', destination='module-01-section-2';
const original=personalCourseSnapshot(publishedPersonalCourse).allRows.find(row=>row.kind==='core');
const originalLesson=personalCourseSnapshot(publishedPersonalCourse).course.modules.flatMap(m=>m.lessons).find(l=>l.id===original.id);
const add={type:'add',url:originalLesson.url,title:originalLesson.title,instructor:originalLesson.instructor,sectionId:destination,beforeId:null};
assert.throws(()=>change(publishedPersonalCourse,add),/already in your course/);
let state=change(publishedPersonalCourse,{...add,allowDuplicate:true});
const copy=state.videos.find(v=>v.intentionalDuplicate && v.videoId===originalLesson.videoId);
assert.ok(copy); assert.equal(personalCourseSnapshot(state).byId.get(copy.id).sectionId,destination);
state=parsePersonalCourse(JSON.parse(JSON.stringify(state)));
assert.ok(personalCourseSnapshot(state).byId.has(original.id));
assert.equal(personalCourseSnapshot(state).byId.get(copy.id).sectionId,destination);
state=change(state,{type:'move',id:copy.id,sectionId:section,beforeId:null});
assert.equal(personalCourseSnapshot(state).byId.get(original.id).sectionId,original.sectionId);
state=change(state,{type:'archive',id:copy.id});
assert.ok(personalCourseSnapshot(state).byId.has(original.id));
assert.ok(!personalCourseSnapshot(state).byId.has(copy.id));
state=change(state,{...add,allowDuplicate:true});
assert.equal(state.videos.filter(v=>v.videoId===originalLesson.videoId).length,2);
assert.equal(parsePersonalCourse(state).videos.filter(v=>v.videoId===originalLesson.videoId).length,2);
assert.throws(()=>change(state,{...add,allowDuplicate:'yes'}),/Invalid duplicate choice/);
state=change(state,{type:'delete',id:copy.id});
state=parsePersonalCourse(state);
assert.ok(personalCourseSnapshot(state).byId.has(original.id));
assert.equal(state.videos.filter(v=>v.videoId===originalLesson.videoId).length,1);
console.log('PASS: explicit copies of published and personal videos survive reload, move and archive independently; unconfirmed duplicates remain blocked.');
