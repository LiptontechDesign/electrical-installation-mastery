import assert from 'node:assert/strict';
import { build } from 'esbuild';
await build({ entryPoints: ['app/learner-state.ts', 'app/flexible-progress.ts'], outdir: 'work/state-tests', bundle: true, platform: 'node', format: 'esm' });
const { clampState, initialLearnerState, isProgressBackup } = await import('../work/state-tests/learner-state.js');
const { recordVideoCompletion } = await import('../work/state-tests/flexible-progress.js');
const retired = ['assessment', 'evidence', 'completedReadingIds', 'completedLabIds', 'confidence', 'reviewBeforeNext', 'lessonQuizBestScores', 'moduleQuizBestScores', 'checkpointQuizBestScores', 'quizRecords', 'flashcardProgress'];
const old = { ...initialLearnerState, schemaVersion: 9, activeLessonId: 'p05-l07', completedLessonIds: ['p01-l01', 'p01-l01', 'invalid'], bookmarkedLessonIds: ['p05-l07'], notes: { 'p05-l07': 'My own notes' }, videoCompletionCounts: { 'p01-l01': 4 }, studyMinutesByDate: { '2026-09-11': 37 }, autoNextEnabled: false, ...Object.fromEntries(retired.map(key => [key, { retired: true }])) };
const migrated = clampState(old);
assert.equal(migrated.schemaVersion, 10);
for (const key of retired) assert.ok(!(key in migrated), key + ' is removed from saved state');
assert.deepEqual(migrated.completedLessonIds, ['p01-l01']);
for (const key of ['activeLessonId', 'bookmarkedLessonIds', 'notes', 'videoCompletionCounts', 'studyMinutesByDate', 'autoNextEnabled']) assert.deepEqual(migrated[key], old[key], key + ' is preserved');
assert.deepEqual(clampState(migrated), migrated, 'Migration is idempotent');
const complete = recordVideoCompletion(migrated, 'p01-l01');
assert.equal(complete.completedLessonIds.length, 1);
assert.equal(complete.videoCompletionCounts['p01-l01'], 5);
assert.ok(isProgressBackup(old, new Set(['p05-l07'])));
assert.ok(isProgressBackup(migrated, new Set(['p05-l07'])));
assert.equal(isProgressBackup({ ...old, schemaVersion: 11 }, new Set(['p05-l07'])), false);
for (const invalid of [null, [], {}, 'broken', 17]) assert.doesNotThrow(() => clampState(invalid));
const malformed = clampState({ ...old, notes: [], videoCompletionCounts: { 'p01-l01': Infinity }, studyMinutesByDate: { '2026-09-11': Infinity } });
assert.deepEqual(malformed.videoCompletionCounts, {});
assert.deepEqual(malformed.studyMinutesByDate, {});
console.log('PASS: older backups migrate to video-only state while preserving notes, bookmarks, watched records and playback preferences.');

const withPlayback = clampState({ ...initialLearnerState, videoPositions: { abcdefghijk: 72.8, bad: 12, lmnopqrstuv: -1, wxyzabcdefg: Infinity }, timestampNotes: { abcdefghijk: [{ id: 'note1', seconds: 42.9, text: 'My timestamp note' }, { id: 'bad', seconds: -5, text: 'Invalid' }] } });
assert.deepEqual(withPlayback.videoPositions, { abcdefghijk: 72 });
assert.deepEqual(withPlayback.timestampNotes, { abcdefghijk: [{ id: 'note1', seconds: 42, text: 'My timestamp note' }] });
assert.deepEqual(clampState(withPlayback), withPlayback, 'Playback and notes survive server parsing and backup restore');
assert.deepEqual(clampState({ schemaVersion: 9 }).videoPositions, {}, 'Old backups start with no saved positions');
assert.deepEqual(clampState({ videoPositions: [], timestampNotes: 'bad' }).timestampNotes, {});
console.log('PASS: playback positions and timestamp notes are validated and migrate safely.');

const optionalDetails = clampState({ videoBookmarks: ['abcdefghijk','bad','abcdefghijk'], videoNotes: { abcdefghijk: 'Personal optional note', bad: 'bad ID', lmnopqrstuv: 42 } });
assert.deepEqual(optionalDetails.videoBookmarks, ['abcdefghijk']);
assert.deepEqual(optionalDetails.videoNotes, { abcdefghijk: 'Personal optional note' });
